                <p class="text-gray-600">Anda dapat melihat riwayat transaksi dengan mengklik menu "Riwayat" di bagian atas halaman. Di sana, Anda bisa melihat semua transaksi yang telah selesai dan memfilternya berdasarkan tanggal.</p>
