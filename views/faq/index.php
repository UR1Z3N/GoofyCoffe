                <p class="text-gray-600">Setelah semua pesanan masuk ke keranjang, klik tombol "Proses Pembayaran" berwarna hijau di bagian bawah keranjang. Pilih metode pembayaran (Tunai atau Digital), lalu klik "Selesaikan Pesanan".</p>
            </div>

